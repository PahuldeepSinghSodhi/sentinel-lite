"""Private S3 object adapter. Authorization stays in the owning repository layer."""
from pathlib import PurePosixPath

from app.cloud.aws_clients import client
from app.cloud.settings import BUCKET


def valid_path(path):
    if not path or PurePosixPath(path).is_absolute() or ".." in PurePosixPath(path).parts or "\\" in path:
        raise ValueError("Invalid private object path")
    return path


def put(path, data, content_type="application/octet-stream"):
    client("s3").put_object(Bucket=BUCKET, Key=valid_path(path), Body=data,
                            ContentType=content_type, ServerSideEncryption="AES256")


def get(path):
    from botocore.exceptions import ClientError
    try:
        body = client("s3").get_object(Bucket=BUCKET, Key=valid_path(path))["Body"]
    except ClientError as exc:
        if exc.response["Error"]["Code"] in {"NoSuchKey", "404"}:
            raise FileNotFoundError("Private case object is missing") from exc
        raise
    try:
        return body.read()
    finally:
        body.close()


def delete(paths):
    for i in range(0, len(paths), 1000):
        result = client("s3").delete_objects(Bucket=BUCKET, Delete={
            "Objects": [{"Key": valid_path(path)} for path in paths[i:i + 1000]], "Quiet": True})
        if result.get("Errors"):
            raise RuntimeError("Private object cleanup failed; retry")


def signed_download(path, filename, inline=False):
    # Names are generated by the app; prevent header injection even if a row is corrupt.
    filename = "".join(c for c in filename if c.isascii() and (c.isalnum() or c in "-_."))[:100] or "download"
    parameters = {
        "Bucket": BUCKET, "Key": valid_path(path),
        "ResponseContentDisposition": f'{"inline" if inline else "attachment"}; filename="{filename}"'}
    if filename.endswith(".pdf"):
        parameters["ResponseContentType"]="application/pdf"
    return client("s3").generate_presigned_url("get_object", Params=parameters, ExpiresIn=300)
